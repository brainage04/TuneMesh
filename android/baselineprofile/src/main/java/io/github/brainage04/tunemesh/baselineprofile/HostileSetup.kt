package io.github.brainage04.tunemesh.baselineprofile

import android.os.Environment
import android.os.SystemClock
import androidx.benchmark.macro.MacrobenchmarkScope
import androidx.test.platform.app.InstrumentationRegistry
import androidx.test.uiautomator.By
import androidx.test.uiautomator.BySelector
import androidx.test.uiautomator.Direction
import androidx.test.uiautomator.StaleObjectException
import androidx.test.uiautomator.UiDevice
import androidx.test.uiautomator.Until
import io.github.brainage04.tunemesh.HostileLibrary
import java.io.File

const val PACKAGE = "io.github.brainage04.tunemesh"

/**
 * The hostile library of `docs/library-format.md` "Limits" in the app's default library folder (emulator only), and the UI steps the
 * benchmarks and the baseline profile generator share.
 *
 * Instrumentation argument `hostileScale`: `full` (default: 100,000 files, a 40,000-track album, 250,000-entry playlists) or `small`.
 */
object HostileSetup {
    @Suppress("DEPRECATION") private val root = File(Environment.getExternalStorageDirectory(), "Music/TuneMesh")

    /** Generates the library once per device; a folder holding anything else is never touched. */
    fun ensureLibrary() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        shell("appops set --uid ${instrumentation.context.packageName} MANAGE_EXTERNAL_STORAGE allow")
        val small = InstrumentationRegistry.getArguments().getString("hostileScale") == "small"
        val marker = File(root, ".tunemesh-benchmark-${if (small) "small" else "full"}")
        if (marker.isFile) return
        // The app's own .stignore is all an unused library folder holds.
        val entries = root.list().orEmpty().filterNot { it == ".stignore" }
        check(entries.isEmpty() || entries.any { it.startsWith(".tunemesh-benchmark-") }) {
            "$root holds another library; move it away before benchmarking"
        }
        HostileLibrary(root, if (small) HostileLibrary.Scale.SMALL else HostileLibrary.Scale.FULL).generate()
        marker.writeText("generated by HostileSetup\n")
    }

    private fun shell(command: String) {
        InstrumentationRegistry.getInstrumentation().uiAutomation.executeShellCommand(command).close()
    }
}

/** Starts the app if it is not running, past the onboarding, and waits until the library is shown and the app has settled. */
fun MacrobenchmarkScope.openApp() {
    device.executeShellCommand("appops set --uid $PACKAGE MANAGE_EXTERNAL_STORAGE allow")
    if (device.executeShellCommand("pidof $PACKAGE").isBlank()) startActivityAndWait()
    skipSyncthingSetup()
    waitForLibrary()
}

/** The onboarding's Syncthing step, shown on the first start after an install: its "Skip for now" is below the fold. */
fun MacrobenchmarkScope.skipSyncthingSetup() {
    if (!device.wait(Until.hasObject(By.text("Sync your library")), 2_000)) return
    device.findObject(By.scrollable(true))?.scrollUntil(Direction.DOWN, Until.findObject(By.text("Skip for now")))?.click()
    device.waitForIdle(2_000)
}

/** Waits until Home shows the scanned library and its playlists, then until the app stops using the CPU. */
fun MacrobenchmarkScope.waitForLibrary() {
    tab("Home")
    check(device.wait(Until.hasObject(By.text("Recently added")), SCAN_TIMEOUT_MS)) { "the library did not load" }
    check(device.wait(Until.hasObject(By.text("Your playlists")), SCAN_TIMEOUT_MS)) { "the playlists did not load" }
    waitUntilIdle()
}

/**
 * Waits until the app process uses less than a tenth of a CPU for three seconds in a row (the first scan of the hostile library takes
 * minutes; every later step should start from a quiet app).
 */
fun MacrobenchmarkScope.waitUntilIdle(timeoutMs: Long = SCAN_TIMEOUT_MS) {
    val end = SystemClock.uptimeMillis() + timeoutMs
    var quiet = 0
    var last = cpuTicks()
    while (SystemClock.uptimeMillis() < end && quiet < 3) {
        Thread.sleep(1_000)
        val now = cpuTicks()
        quiet = if (now - last <= 10) quiet + 1 else 0
        last = now
    }
}

private fun MacrobenchmarkScope.cpuTicks(): Long {
    val pid = device.executeShellCommand("pidof $PACKAGE").trim().substringBefore(' ')
    if (pid.isEmpty()) return 0
    // Fields after the parenthesised name; utime and stime are fields 14 and 15 of /proc/<pid>/stat.
    val fields = device.executeShellCommand("cat /proc/$pid/stat").substringAfterLast(") ").split(' ')
    return (fields.getOrNull(11)?.toLongOrNull() ?: 0) + (fields.getOrNull(12)?.toLongOrNull() ?: 0)
}

/** Selects a bottom-bar tab; selecting the current tab returns it to its root screen. */
fun MacrobenchmarkScope.tab(label: String) {
    click(By.text(label))
    click(By.text(label))
}

/** Searches for [text] and opens the first result that is not the search field. */
fun MacrobenchmarkScope.searchFor(text: String) {
    tab("Search")
    val field = device.wait(Until.findObject(By.clazz("android.widget.EditText")), 10_000) ?: error("no search field")
    field.text = text
    check(device.wait(Until.hasObject(By.textContains(text).clazz("android.widget.TextView")), 60_000)) { "no result for $text" }
}

fun MacrobenchmarkScope.openSearchResult(text: String) {
    click(By.textContains(text).clazz("android.widget.TextView"))
}

fun MacrobenchmarkScope.fling(times: Int) {
    repeat(times) {
        try {
            device.findObject(By.scrollable(true))?.fling(Direction.DOWN)
        } catch (_: StaleObjectException) {
            // The list recomposed between finding and flinging; the next fling finds it again.
        }
        device.waitForIdle(2_000)
    }
}

fun MacrobenchmarkScope.click(selector: BySelector) {
    repeat(5) {
        val target = device.wait(Until.findObject(selector), 30_000) ?: error("nothing on screen matches $selector")
        try {
            target.click()
            device.waitForIdle(2_000)
            return
        } catch (_: StaleObjectException) {
            Thread.sleep(200)
        }
    }
    error("$selector kept changing")
}

fun UiDevice.waitFor(selector: BySelector, timeoutMs: Long = 60_000) {
    check(wait(Until.hasObject(selector), timeoutMs)) { "timed out waiting for $selector" }
}

private const val SCAN_TIMEOUT_MS = 60 * 60 * 1000L
